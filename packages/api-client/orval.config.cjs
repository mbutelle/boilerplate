// Le schéma exporté par l'API dans le volume partagé (cible make sdk).
// OPENAPI_SCHEMA permet de générer hors conteneur, sans quoi la génération n'est
// vérifiable que depuis la stack complète.
const schema = process.env.OPENAPI_SCHEMA || '/var/shared/openapi_schema.json'

const header = info => [
  `Generated by orval 🍺`,
  `Do not edit manually.`,
  ...(info.title ? [info.title] : []),
  ...(info.description ? [info.description] : []),
  ...(info.version ? [`OpenAPI spec version: ${info.version}`] : []),
]

module.exports = {
  // 1. Le client : hooks vue-query + types.
  client: {
    input: { target: schema },
    output: {
      // Un dossier par tag OpenAPI sous src/api, tous les DTO centralisés dans
      // src/api/model, avec des index barrels.
      mode: 'tags-split',
      client: 'vue-query',
      // orval 8 génère par défaut des appels façon fetch — `mutator(url, init)`.
      // Notre mutator est une instance axios et attend `mutator(config, options)`.
      httpClient: 'axios',
      target: './src/api/bp.ts',
      schemas: './src/api/model',
      indexFiles: true,
      // Sans clean, une opération retirée de l'API laisse son fichier généré
      // derrière elle : le SDK continue d'exposer un endpoint qui n'existe plus.
      clean: true,
      prettier: true,
      override: {
        // orval 8 enveloppe par défaut les réponses dans `{ data, status }`.
        // Notre mutator déballe déjà (`.then(({ data }) => data)`), si bien que
        // les types annonceraient une enveloppe que le runtime ne produit pas.
        fetch: {
          includeHttpResponseReturnType: false,
        },
        mutator: {
          path: './src/http/CustomHttpClient.ts',
          name: 'CustomHttpClient',
        },
        // NE PAS repositionner `useQuery` / `useMutation` à `true` : depuis
        // orval 8, les poser explicitement les applique à *tous* les verbes, et
        // pour un non-GET le hook query l'emporte sur la mutation — un login
        // finirait mis en cache au lieu d'être une mutation. Les valeurs par
        // défaut font déjà ce qu'on veut : query pour les GET, mutation sinon.
        query: {
          signal: true,
        },
        header,
      },
    },
  },

  // 2. Les schémas zod, dérivés du MÊME contrat.
  //
  // Ils servent deux usages qui étaient jusqu'ici traités à la main :
  //   - valider un formulaire contre les contraintes réellement publiées par
  //     l'API, au lieu de règles recopiées qui finissent par diverger ;
  //   - vérifier une réponse à l'exécution, pour qu'une dérive du back se voie
  //     là où elle se produit plutôt que trois écrans plus loin.
  //
  // fileExtension évite la collision de noms avec les fichiers du client.
  zod: {
    input: { target: schema },
    output: {
      mode: 'tags-split',
      client: 'zod',
      target: './src/api/bp.ts',
      fileExtension: '.zod.ts',
      clean: false,
      prettier: true,
      override: {
        zod: {
          version: 4,
          generate: {
            body: true,
            response: true,
            query: true,
            param: true,
            header: false,
          },
          // Les paramètres de requête arrivent en chaîne depuis l'URL : sans
          // coercition, un `page=2` échouerait sur un schéma attendant un nombre.
          coerce: {
            query: ['string', 'number', 'boolean'],
          },
        },
        header,
      },
    },
  },
}
