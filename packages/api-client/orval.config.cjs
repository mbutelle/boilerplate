module.exports = {
  client: {
    input: {
      // Schéma exporté par l'API dans le volume partagé (cible make sdk).
      // OPENAPI_SCHEMA permet de générer hors conteneur, sans quoi la
      // génération n'est vérifiable que depuis la stack complète.
      target: process.env.OPENAPI_SCHEMA || '/var/shared/openapi_schema.json',
    },
    output: {
      // Un dossier par tag OpenAPI sous src/api, tous les DTO centralisés dans
      // src/api/model, avec des index barrels.
      mode: 'tags-split',
      client: 'vue-query',
      // orval 8 génère par défaut des appels façon fetch — `mutator(url, init)`.
      // Notre mutator est une instance axios et attend `mutator(config, options)`.
      httpClient: 'axios',
      target: './src/api/bp.ts',
      schemas: './src/api/model',
      indexFiles: true,
      override: {
        // orval 8 enveloppe par défaut les réponses dans `{ data, status }`.
        // Notre mutator déballe déjà (`.then(({ data }) => data)`), si bien que
        // les types annonceraient une enveloppe que le runtime ne produit pas.
        fetch: {
          includeHttpResponseReturnType: false,
        },
        mutator: {
          path: './src/http/CustomHttpClient.ts',
          name: 'CustomHttpClient',
        },
        // NE PAS repositionner `useQuery` / `useMutation` à `true` : depuis
        // orval 8, les poser explicitement les applique à *tous* les verbes, et
        // pour un non-GET le hook query l'emporte sur la mutation — un login
        // finirait mis en cache au lieu d'être une mutation. Les valeurs par
        // défaut font déjà ce qu'on veut : query pour les GET, mutation sinon.
        query: {
          signal: true,
        },
        header: info => [
          `Generated by orval 🍺`,
          `Do not edit manually.`,
          ...(info.title ? [info.title] : []),
          ...(info.description ? [info.description] : []),
          ...(info.version ? [`OpenAPI spec version: ${info.version}`] : []),
        ],
      },
    },
  },
}
